import { log } from "@lib/logger";
import fs from "fs/promises";
import path from "path";

const entryDir = path.resolve("./commands");
const generatedDir = path.resolve("./src/generated");
const commandFile = path.join(generatedDir, "commands.js");
const menuFile = path.join(generatedDir, "menu.js");
const docsFile = path.resolve("./docs/commands.md");

const files: string[] = [];

async function collect(dir: string): Promise<void> {
  const entries = await fs.readdir(dir, {
    withFileTypes: true,
  });

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      await collect(fullPath);
      continue;
    }

    if (
      (entry.isFile() && path.extname(entry.name) === ".ts") ||
      path.extname(entry.name) === ".js"
    ) {
      files.push(fullPath);
    }
  }
}

await collect(entryDir);
files.sort();

await fs.mkdir(generatedDir, { recursive: true });
await fs.mkdir(path.dirname(docsFile), { recursive: true });

const imports: string[] = [];
const commands: string[] = [];

for (const [index, file] of files.entries()) {
  const variable = `_${index}`;

  let importPath = path.relative(generatedDir, file);
  importPath = importPath.replaceAll(path.sep, "/");

  if (!importPath.startsWith(".")) {
    importPath = `./${importPath}`;
  }

  imports.push(`import ${variable} from "${importPath}";`);
  commands.push(variable);
}

const commandsLine = `export const commands = [${commands}];`;

const generatedCommands = [
  "// This file is generated. Do not edit manually.",
  "",
  ...imports,
  "",
  commandsLine,
  "",
].join("\n");

await fs.writeFile(commandFile, generatedCommands, "utf8");

// Import only after writing the registry so newly added commands are included
// in this same generator run.
const { commands: cmds } = await import("../generated/commands");

import type { Category, Command } from "../types/command";
import type { FlagSpec } from "@lib/args";
import { config } from "config";

const categoryTitles: Record<Category, string> = {
  tools: "Tools",
  downloader: "Downloader",
  search: "Search",
  admin: "Group administration",
  nsfw: "NSFW",
  ai: "AI",
  game: "Game",
  maker: "Maker",
  uncategorized: "Uncategorized",
};

const menuGroups: Record<string, any[]> = Object.keys(categoryTitles).reduce(
  (acc, key) => {
    acc[key] = [];
    return acc;
  },
  {} as Record<string, any[]>,
);

for (const cmd of cmds) {
  const category =
    cmd.category && menuGroups[cmd.category] ? cmd.category : "uncategorized";
  const title = cmd.name;
  const description = cmd.description || "No description provided";

  menuGroups[category]!.push({
    title,
    description,
    id: `${config.prefix}${title} --help`,
  });
}

const menuEntries = Object.entries(categoryTitles).map(([key, title]) => {
  const rows = menuGroups[key] || [];
  const rowsStr = rows
    .map(
      (r) =>
        `    { title: ${JSON.stringify(r.title)}, description: ${JSON.stringify(r.description)}, id: ${JSON.stringify(r.id)} },`,
    )
    .join("\n");

  return `  ${key}: {\n    title: ${JSON.stringify(title)},\n    rows: [\n${rowsStr}\n    ],\n  },`;
});

const generatedMenu = [
  "// This file is generated. Do not edit manually.",
  "",
  "export const MENU = {",
  ...menuEntries,
  "};",
  "",
].join("\n");

await fs.writeFile(menuFile, generatedMenu, "utf8");

// Keep the command reference derived from the command definitions themselves.
// The menu is a UI representation and intentionally does not own documentation data.
function escapeCell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ").trim();
}

function formatFlagDetails(command: Command): string[] {
  const flags = command.flags ?? [];
  if (flags.length === 0) return [];

  const details = flags.map((flag) => {
    const names = flag.names.map((name) => `\`${name}\``).join(", ");
    const argument =
      flag.kind === "bool"
        ? ""
        : flag.kind === "json"
          ? " <json>"
          : flag.kind === "list"
            ? " <item,...>"
            : " <value>";
    const description = flag.getDescription();
    return `- ${names}${argument}${description ? `: ${description}` : ""}`;
  });

  return [
    `#### \`${command.name}\``,
    "",
    ...details,
    "",
  ];
}

const groupedCommands = new Map<Category, Command[]>();
for (const command of cmds as Command[]) {
  const category =
    command.category && categoryTitles[command.category]
      ? command.category
      : "uncategorized";
  const group = groupedCommands.get(category) ?? [];
  group.push(command);
  groupedCommands.set(category, group);
}

const docLines = [
  "<!-- This file is generated by `bun run generate`. Do not edit manually. -->",
  "",
  "# Commands",
  "",
  "All commands and plugins currently available in violajs.",
  "",
  "## Categories",
  "",
];

for (const [category, title] of Object.entries(categoryTitles) as [Category, string][]) {
  const group = groupedCommands.get(category);
  if (group?.length) {
    docLines.push(`- [${title}](#${title.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")})`);
  }
}

for (const [category, title] of Object.entries(categoryTitles) as [Category, string][]) {
  const group = groupedCommands.get(category);
  if (!group?.length) continue;

  group.sort((a, b) => a.name.localeCompare(b.name));
  docLines.push("", `## ${title}`, "");
  docLines.push("| Command | Aliases | Description | Flags |");
  docLines.push("| --- | --- | --- | --- |");

  for (const command of group) {
    const aliases = command.aliases?.length
      ? command.aliases.map((alias) => `\`${alias}\``).join(", ")
      : "—";
    const description = command.description
      ? escapeCell(command.description)
      : "—";
    const flags = command.flags?.length
      ? `[${command.flags.length} flags](#${command.name.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")})`
      : "—";

    docLines.push(
      `| \`${escapeCell(command.name)}\` | ${aliases} | ${description} | ${flags} |`,
    );
  }

  const commandsWithFlags = group.filter((command) => command.flags?.length);
  if (commandsWithFlags.length) {
    docLines.push("", "### Flag details", "");
    for (const command of commandsWithFlags) {
      docLines.push(...formatFlagDetails(command));
    }
  }
}

docLines.push(
  "",
  "---",
  "",
  "This document is generated from the command definitions in `commands/`. Update the command metadata in its source file, then run `bun run generate`.",
  "",
);

await fs.writeFile(docsFile, docLines.join("\n"), "utf8");

log.info(`Generated ${files.length} commands, menu, and command documentation successfully.`);
