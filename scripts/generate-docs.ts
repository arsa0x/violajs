import fs from "fs/promises";
import path from "path";
import type { Category, CommandPlugin } from "@src/types/command";
import { CATEGORY_TITLES } from "@utils/category";

const entryDir = path.resolve("./plugins/commands");
const docsFile = path.resolve("site/docs/03-command-list.md");

async function collectCommandFiles(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files: string[] = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await collectCommandFiles(fullPath)));
    } else if (
      entry.isFile() &&
      [".ts", ".js"].includes(path.extname(entry.name))
    ) {
      files.push(fullPath);
    }
  }

  return files;
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function escapeCell(value: string): string {
  return value
    .replaceAll("|", "\\|")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("\n", " ")
    .trim();
}

function formatFlagDetails(command: CommandPlugin): string[] {
  const flags = command.flags ?? [];
  if (flags.length === 0) return [];

  const details = flags.map((flag) => {
    const names = flag.names.map((name) => "\x60" + name + "\x60").join(", ");
    const argument =
      flag.kind === "bool"
        ? ""
        : flag.kind === "json"
          ? " `<json>`"
          : flag.kind === "list"
            ? " `<item,...>`"
            : " `<value>`";
    const description = flag.getDescription();

    return "- " + names + argument + (description ? ": " + description : "");
  });

  return ["#### " + "\x60" + command.name + "\x60", "", ...details, ""];
}

const files = (await collectCommandFiles(entryDir)).sort();
const commands: CommandPlugin[] = [];

for (const file of files) {
  const imported = await import(file);
  const command = imported.default as CommandPlugin | undefined;

  if (!command?.name) {
    throw new Error(
      "Command module does not have a default command export: " + file,
    );
  }

  commands.push(command);
}

const groupedCommands = new Map<Category, CommandPlugin[]>();

for (const command of commands) {
  const category =
    command.category && CATEGORY_TITLES[command.category]
      ? command.category
      : "uncategorized";
  const group = groupedCommands.get(category) ?? [];
  group.push(command);
  groupedCommands.set(category, group);
}

const docLines = [
  "<!-- This file is generated by " +
    "\x60bun run docs:generate\x60" +
    ". Do not edit manually. -->",
  "",
  "# 03 — Command List",
  "",
  "All commands currently available in violajs.",
  "",
  "## Categories",
  "",
];

for (const [category, title] of Object.entries(CATEGORY_TITLES) as [
  Category,
  string,
][]) {
  if (groupedCommands.get(category)?.length) {
    docLines.push("- [" + title + "](#" + slug(title) + ")");
  }
}

for (const [category, title] of Object.entries(CATEGORY_TITLES) as [
  Category,
  string,
][]) {
  const group = groupedCommands.get(category);
  if (!group?.length) continue;

  group.sort((a, b) => a.name.localeCompare(b.name));
  docLines.push("", "## " + title, "");
  docLines.push("| Command | Aliases | Description | Usage | Flags |");
  docLines.push("| --- | --- | --- | --- | --- |");

  for (const command of group) {
    const aliases = command.aliases?.length
      ? command.aliases
          .map((alias) => "\x60" + escapeCell(alias) + "\x60")
          .join(", ")
      : "—";
    const description = command.description
      ? escapeCell(command.description)
      : "—";
    const usage = command.usage?.length
      ? command.usage.map((item) => `\`${item}\``).join("<br>")
      : "—";
    const flags = command.flags?.length
      ? "[" + command.flags.length + " flags](#" + slug(command.name) + ")"
      : "—";

    docLines.push(
      "| " +
        "\x60" +
        escapeCell(command.name) +
        "\x60" +
        " | " +
        aliases +
        " | " +
        description +
        " | " +
        usage +
        " | " +
        flags +
        " |",
    );
  }

  const commandsWithFlags = group.filter((command) => command.flags?.length);
  if (commandsWithFlags.length) {
    docLines.push("", "### Flag details", "");
    for (const command of commandsWithFlags) {
      docLines.push(...formatFlagDetails(command));
    }
  }
}

docLines.push(
  "",
  "---",
  "",
  "This document is generated from the command definitions in " +
    "\x60commands/\x60" +
    ". Update the command metadata in its source file, then run " +
    "\x60bun run docs:generate\x60" +
    ".",
  "",
);

await fs.mkdir(path.dirname(docsFile), { recursive: true });
await fs.writeFile(docsFile, docLines.join("\n"), "utf8");

console.info(
  "Generated command documentation for " + commands.length + " commands.",
);
